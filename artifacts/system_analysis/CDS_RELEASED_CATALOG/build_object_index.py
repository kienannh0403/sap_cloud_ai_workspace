"""Build the non-CDS part of the released-object catalog: classes, interfaces, BDEFs, BAdIs, function groups,
authorization objects — one CSV per type under released_objects/.

The CDS catalog (build_catalog.py) keeps only DDLS; this script covers the rest of the same SAP file, so a
lookup for "is CL_X / IF_X / I_XTP behavior / BAdI X released?" never needs a guess.

Run from the workspace root:
    python -X utf8 artifacts/system_analysis/CDS_RELEASED_CATALOG/build_object_index.py            # download + build
    python -X utf8 artifacts/system_analysis/CDS_RELEASED_CATALOG/build_object_index.py <file.json> # build from a local copy

refresh_sap_official.py calls build() with the list it already downloaded, so both catalogs stay on one SAP version.
Source: github.com/SAP/abap-atc-cr-cv-s4hc, src/objectReleaseInfoLatest.json (S/4HANA Cloud Public Edition).
"""
import collections
import csv
import datetime
import json
import os
import sys
import urllib.request

OUT = "artifacts/system_analysis/CDS_RELEASED_CATALOG"
INDEX_DIR = os.path.join(OUT, "released_objects")
RAW_URL = "https://raw.githubusercontent.com/SAP/abap-atc-cr-cv-s4hc/main/src/objectReleaseInfoLatest.json"
SOURCE_URL = "https://github.com/SAP/abap-atc-cr-cv-s4hc/blob/main/src/objectReleaseInfoLatest.json"
COMMITS_API = ("https://api.github.com/repos/SAP/abap-atc-cr-cv-s4hc/commits"
               "?path=src/objectReleaseInfoLatest.json&per_page=1")

# tadirObject -> (file stem, what it is). DDLS lives in the CDS catalog; TABL/DTEL/TTYP/DOMA are left out on
# purpose (types only, looked up through the CDS/class that uses them).
TYPES = {
    "CLAS": ("CLAS", "classes"),
    "INTF": ("INTF", "interfaces"),
    "BDEF": ("BDEF", "behavior definitions (RAP BOs callable with EML)"),
    "ENHS": ("BADI", "BAdI definitions (object_key = BAdI name, tadir_name = enhancement spot)"),
    "FUGR": ("FUGR", "function groups (released = callable function modules inside)"),
    "SUSO": ("SUSO", "authorization objects"),
}
COLUMNS = ["object_key", "tadir_name", "object_type", "state", "app_component", "software_component", "successors"]


def _row(obj):
    successors = ";".join(s.get("objectKey") or s.get("tadirObjName", "") for s in obj.get("successors", []))
    return {
        "object_key": obj["objectKey"],
        "tadir_name": obj["tadirObjName"],
        "object_type": obj["objectType"],
        "state": obj["state"],
        "app_component": obj.get("applicationComponent", ""),
        "software_component": obj.get("softwareComponent", ""),
        "successors": successors,
    }


def _read_existing(path):
    if not os.path.exists(path):
        return {}
    with open(path, encoding="utf-8", newline="") as fh:
        return {r["object_key"]: r["state"] for r in csv.DictReader(fh)}


def build(objects, sap_last_update):
    """Write released_objects/<TYPE>.csv + README.md; return one summary line per type (released added/dropped)."""
    os.makedirs(INDEX_DIR, exist_ok=True)
    by_type = collections.defaultdict(list)
    for obj in objects:
        if obj["tadirObject"] in TYPES:
            by_type[obj["tadirObject"]].append(_row(obj))

    summary, table = [], []
    for tadir, (stem, label) in TYPES.items():
        rows = sorted(by_type[tadir], key=lambda r: (r["object_key"], r["tadir_name"]))
        path = os.path.join(INDEX_DIR, f"{stem}.csv")
        old = _read_existing(path)
        new = {r["object_key"]: r["state"] for r in rows}
        added = sorted(k for k, s in new.items() if s == "released" and old.get(k) != "released")
        dropped = sorted(k for k, s in old.items() if s == "released" and new.get(k) != "released")
        with open(path, "w", encoding="utf-8", newline="") as fh:
            writer = csv.DictWriter(fh, fieldnames=COLUMNS)
            writer.writeheader()
            writer.writerows(rows)
        states = collections.Counter(r["state"] for r in rows)
        table.append(f"| `{stem}.csv` | {label} | {states['released']} | {states['deprecated']} "
                     f"| {states['notToBeReleased']} |")
        if old:
            summary.append(f"{stem}: +{len(added)} released, -{len(dropped)} no longer released"
                           + (f" (new: {', '.join(added[:15])}{' …' if len(added) > 15 else ''})" if added else ""))
        else:
            summary.append(f"{stem}: first build, {states['released']} released")

    readme = f"""# Released objects other than CDS (S/4HANA Cloud Public Edition)

Generated by `../build_object_index.py` — do not edit by hand. SAP list version: **{sap_last_update}**
(built {datetime.date.today().isoformat()}). Source: [{SOURCE_URL}]({SOURCE_URL}).
CDS views are in the main catalog (`../INDEX.md`), not here.

| File | Content | released | deprecated | notToBeReleased |
|---|---|---|---|---|
{chr(10).join(table)}

## How to look up

- One object: `grep -i "^CL_ABAP_TX," released_objects/CLAS.csv` (first column is the name, upper case).
- By area: `grep ",SD-" released_objects/BDEF.csv` — `app_component` is SAP's application component.
- BAdI: search `BADI.csv` by BAdI name (`object_key`) or by enhancement spot (`tadir_name`).

## Reading the state

- `released` — usable in ABAP Cloud (C1). This is the only state a TS may build on.
- `deprecated` — still works, will go away; `successors` names the replacement. Never plan new code on it.
- `notToBeReleased` — SAP decided it stays internal. Find another way (decision ladder), do not wait for it.
- Not in the file at all — not released. Same as above; never invent a released name.
"""
    with open(os.path.join(INDEX_DIR, "README.md"), "w", encoding="utf-8") as fh:
        fh.write(readme)
    return summary


def main():
    if len(sys.argv) > 1:
        with open(sys.argv[1], encoding="utf-8") as fh:
            raw = json.load(fh)
        sap_date = "local file " + os.path.basename(sys.argv[1])
    else:
        headers = {"User-Agent": "released-object-index"}
        with urllib.request.urlopen(urllib.request.Request(RAW_URL, headers=headers), timeout=300) as resp:
            raw = json.loads(resp.read())
        try:  # SAP's own update date, same value refresh_sap_official.py records
            with urllib.request.urlopen(urllib.request.Request(COMMITS_API, headers=headers), timeout=15) as resp:
                sap_date = json.loads(resp.read())[0]["commit"]["committer"]["date"][:10]
        except Exception:
            sap_date = f"unknown (downloaded {datetime.date.today().isoformat()})"
    for line in build(raw["objectReleaseInfo"], sap_date):
        print(line)


if __name__ == "__main__":
    main()
